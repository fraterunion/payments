const ISO_4217_PAYMENT_CODE_SET: ReadonlySet<string> = new Set(ISO_4217_PAYMENT_CODES);

const CURRENCY_PATTERN = /^[A-Z]{3}$/;

export type CurrencyCode = (typeof ISO_4217_PAYMENT_CODES)[number];

export function isCurrencyCode(value: string): value is CurrencyCode {
  return ISO_4217_PAYMENT_CODE_SET.has(value);
}

/**
 * Canonicalizes a currency code to uppercase ISO 4217.
 * Rejects empty, non-letter, wrong-length, and non-listed codes.
 */
export function canonicalizeCurrencyCode(value: string): CurrencyCode {
  const canonical = value.trim().toUpperCase();
  if (!CURRENCY_PATTERN.test(canonical)) {
    throw new InvalidMoneyError(
      'Currency must be exactly three ASCII letters (ISO 4217).',
      DOMAIN_ERROR_CODES.INVALID_CURRENCY,
    );
  }
  if (!isCurrencyCode(canonical)) {
    throw new InvalidMoneyError(
      `Currency "${canonical}" is not an accepted ISO 4217 payment code.`,
      DOMAIN_ERROR_CODES.INVALID_CURRENCY,
    );
  }
  return canonical;
}
